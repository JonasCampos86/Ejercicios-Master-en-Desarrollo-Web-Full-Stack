'''
Permite que el usuario introduzca una letra (del alfabeto latino) como input. Comprueba si esta es
una mayúscula o una minúscula.
'''
#Pedir una letra como el quiera pero del abecedario
letra = input("Escribe una letra del abecedario como tu quieras " )

#comprobamos y le decimos si es minuscula o mayuscula

if letra == letra.upper():
    print("Esta en mayúscula")
else:
    print("Esta en minuscula")
  




